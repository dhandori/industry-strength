def build_jp(ghr: Path, problems: list) -> dict:
    """일본 시장 설정. 종목은 global-high-radar 의 해외 종목 목록(TSE)으로 이름·시가총액을 확인한다."""
    tse = {r["symbol"]: r for r in json.loads((ghr / "data/universe_overseas.json").read_text())["records"] if r.get("exchange") == "TSE"}
    items, seen = [], set()
    for grp, name, codes in JP:
        members = []
        for c in codes:
            r = tse.get(c)
            if not r and c in JP_SUPPLEMENT:
                kn, mc = JP_SUPPLEMENT[c]
                r = {"korean_name": kn, "market_cap_snapshot_local": mc * 1e8}
            if not r:
                problems.append(f"JP {name}: {c} 일본 종목 목록에 없음")
                continue
            members.append({"code": c, "name": r.get("korean_name") or r.get("english_name") or c, "ticker": f"{c}.T",
                            "market": "TSE", "mcap_jpy_eok": round((r.get("market_cap_snapshot_local") or 0) / 1e8)})
        if len(members) < 2:
            problems.append(f"JP {name}: 구성 종목 {len(members)}개뿐")
        if name in seen:
            problems.append(f"JP 이름 중복 {name}")
        seen.add(name)
        items.append({"id": f"jp_{len(items):02d}", "name": name, "group": grp, "members": sorted(members, key=lambda m: -m["mcap_jpy_eok"])})
    names = {i["name"] for i in items}
    sectors = []
    for code, nm, its in JP_SECTORS:
        bad = [x for x in its if x not in names]
        if bad:
            problems.append(f"JP 섹터 {nm}: 없는 세부 산업 {bad}")
        sectors.append({"ticker": f"{code}.T", "code": code, "name": nm, "en": f"NEXT FUNDS TOPIX-17 {nm}", "items": [x for x in its if x in names]})
    return {"label": "일본", "currency": "엔",
            "benchmark": {"name": "TOPIX", "etf": "NEXT FUNDS TOPIX", "ticker": "1306.T", "code": "1306"},
            "benchmark2": {"name": "닛케이225", "etf": "NEXT FUNDS 닛케이225", "ticker": "1321.T", "code": "1321"},
            "items": items, "sectors": sectors}


